const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({});
for(const name of ['reconstruction','verification'])vm.runInContext(fs.readFileSync('ui/'+name+'.js','utf8'),context);
const escape=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const evidence=[{source:'chat',artifactId:'ar',location:'line 3',kind:'reported',note:'Conflicting threshold <script>'}];
let flow={states:[],actions:[{id:'edge',to:'out',from:['in'],label:'Reported filter',reconstruction:{id:'p',review:'draft',evidence}}],artifacts:{ar:{name:'chat.md'}},reconstructions:{p:{id:'p',status:'partial',states:['in','out'],actions:['edge'],evidenceUpdates:[]}}};
const ui=context.SaigenReconstruction.create({getFlow:()=>flow,escape,shortDate:String});
let html=ui.render({id:'out',reconstruction:{id:'p',review:'draft',evidence}});
assert.ok(html.includes('data-state-id="out"'));
assert.ok(html.includes('data-connection-id="edge"'));
assert.ok(html.includes('Accept remaining items'));
assert.ok(html.includes('pending relationships'));
assert.ok(!html.includes('<script>'));
flow.reconstructions.p.evidenceUpdates=[{id:'update',proposalId:'p',targetId:'out',review:'draft',evidence}];
html=ui.render({id:'out',reconstruction:{id:'p',review:'accepted',evidence}});
assert.ok(!html.includes('data-state-id="out"'));
assert.ok(html.includes('data-evidence-id="update"'));
assert.ok(html.includes('data-connection-id="edge"'));
assert.ok(html.includes('Review reason'));
const verify=context.SaigenVerification.create({escape,shortDate:String,displayText:String});
html=verify.render({proposals:[{id:'v',digest:'digest',writtenBy:'Agent',createdAt:'now',spec:{originalStateId:'out',reason:'Verify numeric agreement',prerequisites:'Python',resources:'Local only',command:['python','{code:0}'],inputArtifactIds:['input'],codeArtifactIds:['code'],outputs:['out.csv'],criteria:[{method:'numeric-table',atol:0,rtol:0}]}}],attempts:[]});
assert.ok(html.includes('data-verify-approve="v"'));
assert.ok(!html.includes('data-verify-execute'));
assert.ok(html.includes('Prerequisites'));
html=verify.render({proposals:[],comparison:{status:'partial',originalStateId:'old',candidateStateId:'new',criteria:[{criterion:{method:'sha256',output:'out.csv'},status:'different'}]}});
assert.ok(html.includes('Comparison outcome · partial'));
assert.ok(html.includes('data-open="old"'));
assert.ok(html.includes('data-open="new"'));
console.log('Reconstruction UI: item review, evidence additions, explicit verification approval, outcomes and escaping passed.');
