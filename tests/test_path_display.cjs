const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const app=fs.readFileSync("ui/app.js","utf8");
new vm.Script(app);
const flow={states:[],actions:[{code:{repository:"/Users/tester/source"},cwd:"/Users/tester/project/.saigen/runs/run_a/work"}],artifacts:{}};
const context=vm.createContext({flow});
vm.runInContext(fs.readFileSync("ui/paths.js","utf8"),context);
vm.runInContext('const {displayPath,displayText,displayCommand,displayRecord}=SaigenPaths.create(()=>flow,()=>"")',context);
const evaluate=code=>vm.runInContext(code,context);
assert.equal(evaluate('displayPath("/Users/tester/project/input.tsv")'),"./input.tsv");
assert.equal(evaluate('displayPath("/Users/tester/source/step.py")'),"{source}/step.py");
assert.equal(evaluate('displayPath("/Users/tester/project-other/input.tsv")'),"{external:1}/input.tsv");
assert.equal(evaluate('displayText("https://example.com/data/a.tsv")'),"https://example.com/data/a.tsv");
assert.equal(evaluate('displayText("\\\"/Users/tester/project/input file.tsv\\\"")'),'"./input file.tsv"');
context.inline='python3 -c \'print("<svg><rect fill=\\"white\\"/><text x=\\"20\\">plot</text></svg>")\'';
assert.equal(evaluate("displayText(inline)"),context.inline);
context.activity={cwd:"/Users/tester/source",command:context.inline,status:"shell-returned",exitCode:0};
assert.equal(evaluate("displayPath(activity.cwd,activity)"),"{source}");
context.record={terminal:{commands:[context.activity]}};
const before=JSON.stringify(context.record);
assert.equal(evaluate("displayCommand(record)"),context.inline);
evaluate("displayRecord(record)");
assert.equal(JSON.stringify(context.record),before);
console.log("Path display checks passed, including inline code and immutable records.");
