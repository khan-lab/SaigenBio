const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({});
for(const name of ['workflows','details'])vm.runInContext(fs.readFileSync(`ui/${name}.js`,'utf8'),context);
const escape=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let flow={states:[{id:'source',title:'Original calls'}],actions:[],artifacts:{input:{id:'input',name:'calls.csv',role:'input'},output:{id:'output',name:'filtered.csv',role:'output'},code:{id:'code',name:'filter.py',role:'code'},reference:{id:'reference',name:'external.csv',role:'input',storage:'reference'}}};
const deps={getFlow:()=>flow,escape,displayPath:String};
const workflows=context.SaigenWorkflows.create(deps);
const ui=context.SaigenDetails.create({...deps,workflows,fileRows:items=>items.map(a=>`<li>${escape(a.name)}</li>`).join(''),displayCommand:a=>a.command||'',displayRecord:v=>v,displayText:String,shortDate:String});
const n={id:'result',status:'completed',artifactIds:['output']};
flow.actions=[{id:'a',to:'result',from:['source'],inputArtifacts:['input','code'],command:'python filter.py',code:{scriptArtifacts:['code']}}];
const result=ui.render(n);
assert.match(result.inputs,/Original calls/);
assert.match(result.inputs,/calls\.csv/);
assert.match(result.outputs,/filtered\.csv/);
assert.match(result.method,/<details[^>]*><summary>Command and script<\/summary>.*python filter\.py/);
assert.doesNotMatch(result.inputs+result.outputs,/filter\.py|not recorded/);
flow.actions[0].code.explanation={summary:'Keep DP ≥ 5 <script>',recordedBy:'Agent',excerpts:[{artifactId:'code',start:2,end:3,text:'if a < b:\n    keep()'}]};
let html=ui.render(n).method;
assert.ok(html.includes('Keep DP ≥ 5 &lt;script&gt;'));
assert.ok(html.includes('Lines 2–3'));
assert.ok(html.includes('if a &lt; b:'));
assert.ok(html.includes('data-artifact="code"'));
assert.ok(!html.includes('<script>'));
const plan={id:'plan',status:'planned',planParents:['source'],planDetails:'Filter depth',expectedFiles:['filtered.csv']};
assert.match(ui.render(plan).inputs,/Original calls/);
assert.match(ui.render(plan).method,/Filter depth/);
assert.equal(ui.render(plan).outputs,'');
const imported=ui.render({id:'import',status:'imported',artifactIds:['input','reference']});
assert.match(imported.inputs,/calls\.csv/);
assert.equal(imported.outputs,'');
assert.match(imported.history,/Additional references/);
assert.doesNotMatch(imported.history,/execution-details/);
flow.actions[0].inputArtifacts.push('reference');
assert.match(ui.render(n).history,/external\.csv/);
html=ui.render({id:'terminal',origin:'terminal',status:'completed',artifactIds:['output']}).outputs;
assert.ok(html.includes('production by a particular command is not established'));
flow.workflows={proposals:{p:{writtenBy:'Agent',spec:{stages:[{key:'filter',method:{tool:'Python',summary:'Filter depth'},expectedSummary:'Expected result'}],inputBindings:[{artifactId:'input'}],pipeline:{name:'Pipeline',source:'local',revision:'x',contentDigest:'sha'},engine:{name:'nextflow',version:'25.10.4'},configuration:{parameters:{min_dp:5}}}}},runs:{}};
for(const status of ['planned','running','completed','failed','cancelled','unknown']){
 const stage=ui.render({...n,status,workflowProposal:'p',workflowStage:'filter'});
 assert.match(stage.inputs,/whole workflow/);
 assert.match(stage.method,/min_dp/);
 assert.match(stage.method,/Python/);
}
delete flow.workflows.proposals.p.spec.stages[0].method;
html=ui.render({...n,workflowProposal:'p',workflowStage:'filter'}).method;
assert.ok(!html.includes('Method explanation not recorded.'));
assert.equal(Object.values(ui.render({id:'bare',status:'planned',planDetails:' '})).join(''),'');
console.log('State details: file roles, plans, workflow scope, excerpts, legacy records, and escaping passed.');
